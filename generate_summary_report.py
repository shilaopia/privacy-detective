# Calculate coverage per platform
from collections import defaultdict
platform_stats = defaultdict(lambda: {"train": set(), "deploy": set(), "high_risks": [], "group": ""})
for row in DATA:
    g, plat, phase, item, _, _, verdict, risk, note = row
    key = f"{g}|{plat}"
    platform_stats[key]["group"] = g
    if phase == "训练" and verdict != "未提及":
        platform_stats[key]["train"].add(item)
    elif phase == "部署" and verdict != "未提及":
        platform_stats[key]["deploy"].add(item)
    if risk == "高":
        platform_stats[key]["high_risks"].append(item)

# Sort by total coverage desc
stats_list = []
for key, v in platform_stats.items():
    g, plat = key.split("|", 1)
    t = len(v["train"])
    d = len(v["deploy"])
    total = t + d
    pct = round(total / 11 * 100)
    risks = ", ".join(v["high_risks"][:3]) if v["high_risks"] else "—"
    stats_list.append([g, plat, f"{t}/5", f"{d}/6", f"{total}/11 ({pct}%)", risks])

stats_list.sort(key=lambda x: -int(x[4].split("/")[0]))

